from pathlib import Path
import numpy as np,json
from PIL import Image
from scipy.ndimage import gaussian_filter,map_coordinates,distance_transform_edt
D=Path(__file__).resolve().parent;W=D.parent;P=W.parent;B=W/'R_layers_full'
base=np.load(B/'master_height.npz')['height'].astype(float);L=np.load(W/'grain_hierarchy/detail_layers.npz');h,w=base.shape;dx,dy=5.1/(w-1),1.3775/(h-1)
X,Y=np.meshgrid(np.linspace(-2.55,2.55,w),np.linspace(-.84,-2.2175,h));kx,ky=-1.31,-1.35;rx,ry=X-kx,Y-ky;r=np.hypot(rx,ry)
rng=np.random.default_rng(151147)
def ss(a,b,t):
 t=np.clip((t-a)/(b-a),0,1);return t*t*(3-2*t)
def sample(a,x,y):return map_coordinates(a,[(y+.84)/-1.3775*(h-1),(x+2.55)/5.1*(w-1)],order=1,mode='reflect')
# Material coordinates follow the existing longitudinal flow, not concentric rings.
V=Y-.105*np.tanh((Y-ky)/.11)*np.exp(-((X-kx)/.42)**2)
U=X+.008*np.sin(Y*9+X*1.1)
# Quieter intervals are authored spatially and modulate density, not just amplitude.
quiet=.30+.70*(1-.70*np.exp(-((X+.7)/.48)**2-((Y+1.03)/.13)**2))
quiet*=1-.40*np.exp(-((X-1.2)/.65)**2-((Y+1.45)/.20)**2)
plate=1-ss(.003,.014,-L['medium']-L['knot'])
plate*=1-ss(.001,.012,-L['fractures'])
core=1-ss(.80,1.15,np.sqrt((rx/.145)**2+(ry/.17)**2))
plate*=1-.80*core
layers=np.zeros_like(base);small=np.zeros_like(base);wear=np.zeros_like(base)
# Tapered, flat sided, asymmetrical shavings. Broad planes survive between them.
for count,lengths,widths,depths,out in [(330,(.055,.27),(.006,.020),(.0022,.0067),layers),(850,(.026,.14),(.002,.0065),(.0007,.0026),small)]:
 for i in range(count):
  cx=rng.uniform(-2.52,2.52);cy=rng.uniform(-2.21,-.85);le=rng.uniform(*lengths);wi=rng.uniform(*widths);dep=rng.uniform(*depths)
  s=(U-cx)/le;drift=.20*wi*np.sin(2.1*s+rng.uniform(0,6.28));t=(V-cy+drift)/wi
  # Broken ends have different angles and lengths across the fiber width.
  along=ss(-1,-.74,s+.16*t)*(1-ss(.58,1,s-.11*t))
  cross=ss(-1,-.78,t)*(1-ss(.10,.95,t))
  shape=along*cross*(.85+.15*np.clip(s,-1,1))
  out[:]=np.maximum(out,dep*shape)
  if count==330:wear[:]=np.maximum(wear,shape*(.6+.4*rng.random()))
body_fibers=-(layers+small)*plate*quiet
# Retain naturally irregular substructure from the cached real wood height.
scan=np.load(W/'M_scanned_knot/master_height.npz')['height'].astype(float)
sc=gaussian_filter(scan,(.002/dy,.008/dx))-gaussian_filter(scan,(.014/dy,.060/dx))
sc=sample(sc,X,V)
sc=np.clip(sc,-.004,.004)*.32*plate
# Compressed, broken fibers within the existing knot core, no growth rings added.
knot=np.zeros_like(base)
for i in range(26):
 cx=kx+rng.uniform(-.13,.13);cy=ky+rng.uniform(-.15,.15);ang=rng.uniform(-.33,.33)+(cx-kx)*1.9
 u=(X-cx)*np.cos(ang)-(Y-cy)*np.sin(ang);v=(X-cx)*np.sin(ang)+(Y-cy)*np.cos(ang)
 length=rng.uniform(.022,.085);width=rng.uniform(.003,.010);s=v/length;t=u/width
 shape=ss(-1,-.75,s+.17*t)*(1-ss(.50,1,s-.16*t))*ss(-1,-.7,t)*(1-ss(.2,1,t))
 knot=np.maximum(knot,rng.uniform(.002,.0065)*shape)
knot=-knot*core
# Reinforce only the already existing central check, with varying walls and depth.
check_x=kx+.004*np.sin(ry*47)+.010*ry
check_gate=ss(-.19,-.13,ry)*(1-ss(.13,.18,ry))
check_width=.0038+.0017*np.sin(ry*35+.3)+.0008*np.sin(ry*91)
check=-.012*np.clip(1-abs(X-check_x)/check_width,0,1)**.8*check_gate*core
# Minor fiber lifting immediately beside existing fractures, not new crack locations.
dist=distance_transform_edt(L['fractures']>-.003,sampling=(dy,dx))
edge=(1-ss(.003,.017,dist))*ss(.0003,.003,-L['fractures'])
lift=.0015*edge*(.55+.45*np.sin(X*31+Y*4))
full=np.minimum(base+body_fibers+sc+knot+check+lift,0)
assert full.min()>-.075
geometry=gaussian_filter(full,(.0045/dy,.0045/dx));res=full-geometry
gy,gx=np.gradient(res,dy,dx);n=np.stack([-gx,gy,np.ones_like(gx)],2);n/=np.linalg.norm(n,axis=2)[:,:,None]
# Material test is independent of identical sculptural geometry.
rgb=np.asarray(Image.open(B/'albedo.png').convert('RGB'),float)[16:-16,16:-16]/255
rough=np.asarray(Image.open(B/'roughness.png').convert('L'),float)[16:-16,16:-16]/255
srgb=np.asarray(Image.open(W/'M_scanned_knot/albedo.png').convert('RGB'),float)[16:-16,16:-16]/255
lum=srgb@np.array([.2126,.7152,.0722]);broad=gaussian_filter(lum,(.05/dy,.17/dx));broad=sample(broad,X,V)
pig=np.clip((broad/np.median(broad))**.48,.80,1.17)
fine=lum-gaussian_filter(lum,(.006/dy,.03/dx));fine=sample(fine,X,V);fine=np.clip(fine/max(np.std(fine),1e-5),-2,2)
rich=rgb*pig[:,:,None]*(1+.030*fine[:,:,None])
# Knot end grain is intrinsically denser and darker, not a painted light direction.
rich*=1-.29*core[:,:,None]
chestnut=(pig<.96).astype(float);amber=(pig>1.02).astype(float)
rich*=np.stack([1+.025*amber,1-.025*chestnut,1-.04*chestnut],2)
# Exposed fiber pigment is subtle, while its shadow is generated by geometry.
exposure=gaussian_filter(wear*plate,(.001/dy,.004/dx))*.045
rich=rich*(1-exposure[:,:,None])+np.array([.56,.30,.14])*exposure[:,:,None]
richrough=np.clip(rough+.018*(1-pig)/.15+.012*fine-.026*exposure/.045,.55,.83)
np.savez_compressed(D/'surface_layers.npz',base=base.astype('float32'),shaved_fibers=body_fibers.astype('float32'),scanned_detail=sc.astype('float32'),knot_fibers=knot.astype('float32'),central_check=check.astype('float32'),fiber_lift=lift.astype('float32'))
def save(out,name,a):
 pads=((16,16),(16,16))+(((0,0),) if a.ndim==3 else ())
 Image.fromarray(np.uint8(np.clip(np.pad(a,pads,mode='edge'),0,1)*255+.5)).save(out/name)
for key,c,roughness in [('S_fiber_structure',rgb,rough),('T_fiber_material',rich,richrough)]:
 out=W/key;out.mkdir(exist_ok=True)
 save(out,'albedo.png',c);save(out,'roughness.png',roughness);save(out,'normal.png',n*.5+.5)
 np.savez_compressed(out/'surface.npz',height=geometry.astype('float32'));np.savez_compressed(out/'master_height.npz',height=full.astype('float32'))
 d=dict(source_baseline='R_layers_full',source='Existing medium anatomy and fractures plus asymmetrical longitudinal fiber terraces and cached CC0 scan detail',seed=151147,normal_split=.0045,height_min=float(full.min()),primary_groove_and_fracture_positions_preserved=True,knot_center=[kx,ky],new_growth_rings=False,material_variant='R unchanged' if key.startswith('S_') else 'Independent scanned broad pigment, dense knot core, subtle fiber pigment and roughness',layer_file=str(D/'surface_layers.npz'),construction='Only test plank grid changes; original boundary and source chest preserved')
 (out/'design.json').write_text(json.dumps(d,indent=2));print(key,float(full.min()),flush=True)
